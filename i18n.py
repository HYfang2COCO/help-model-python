def localize_error(error, language='zh'):
    text = str(error)
    if language == 'zh':
        return text
    if isinstance(error,json.JSONDecodeError):
        return (f'JSON non valide (ligne {error.lineno}, colonne {error.colno}).' if language=='fr'
                else f'Invalid JSON (line {error.lineno}, column {error.colno}).')
    for key in sorted(ERRORS,key=len,reverse=True):
        if key in text:
            text = text.replace(key,ERRORS[key][0 if language=='fr' else 1])
    if re.search('[\u3400-\u9fff]',text):
        return 'Entrée non valide. Vérifiez le fichier et les paramètres.' if language=='fr' else 'Invalid input. Check the file and parameter values.'
    return text


